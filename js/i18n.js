class I18nManager {
  constructor() {
    this.currentLang = localStorage.getItem('soundrise_language') || 'fr';
    if (!TRANSLATIONS[this.currentLang]) {
      this.currentLang = 'fr';
    }
    this.listeners = [];
  }

  getLanguage() {
    return this.currentLang;
  }

  setLanguage(langCode) {
    if (TRANSLATIONS[langCode]) {
      this.currentLang = langCode;
      localStorage.setItem('soundrise_language', langCode);
      const isRtl = langCode === 'ar';
      if (typeof document !== 'undefined' && document.documentElement) {
        document.documentElement.dir = isRtl ? 'rtl' : 'ltr';
        document.documentElement.lang = langCode;
      }
      this.notifyListeners();
    }
  }

  t(key, fallback = '') {
    const dict = TRANSLATIONS[this.currentLang] || TRANSLATIONS.fr;
    return dict[key] || TRANSLATIONS.fr[key] || TRANSLATIONS.en[key] || fallback || key;
  }

  onChange(callback) {
    this.listeners.push(callback);
  }

  notifyListeners() {
    this.listeners.forEach((cb) => {
      try { cb(this.currentLang); } catch (e) { console.error(e); }
    });
  }
}

export const i18n = new I18nManager();
export const t = (key, fallback = '') => i18n.t(key, fallback);
