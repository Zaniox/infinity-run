export class I18nManager {
  constructor() {
    let saved = 'fr';
    try {
      saved = localStorage.getItem('soundrise_language') || 'fr';
    } catch (_) {}
    this.currentLang = TRANSLATIONS[saved] ? saved : 'fr';
    this.listeners = [];
  }

  getLanguage() {
    return this.currentLang;
  }

  setLanguage(langCode) {
    if (TRANSLATIONS[langCode]) {
      this.currentLang = langCode;
      try {
        localStorage.setItem('soundrise_language', langCode);
      } catch (_) {}
      this.applyToDOM();
      this.notifyListeners();
    }
  }

  t(key, fallback = '', params = null) {
    const dict = TRANSLATIONS[this.currentLang] || TRANSLATIONS.fr;
    let text = dict[key] || TRANSLATIONS.fr[key] || TRANSLATIONS.en[key] || fallback || key;
    if (params && typeof params === 'object') {
      for (const [k, v] of Object.entries(params)) {
        text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
      }
    }
    return text;
  }

  applyToDOM() {
    if (typeof document === 'undefined') return;

    // 1. Text elements
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.dataset.i18n;
      const translated = this.t(key);
      if (translated && translated !== key) {
        if (el.dataset.i18nHtml === 'true') {
          el.innerHTML = translated;
        } else {
          el.textContent = translated;
        }
      }
    });

    // 2. Placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const key = el.dataset.i18nPlaceholder;
      const translated = this.t(key);
      if (translated && translated !== key) {
        el.placeholder = translated;
      }
    });

    // 3. Tooltips and titles
    document.querySelectorAll('[data-i18n-title]').forEach((el) => {
      const key = el.dataset.i18nTitle;
      const translated = this.t(key);
      if (translated && translated !== key) {
        el.title = translated;
      }
    });

    // 4. Update html lang and dir for RTL support
    const isRtl = this.currentLang === 'ar';
    if (document.documentElement) {
      document.documentElement.dir = isRtl ? 'rtl' : 'ltr';
      document.documentElement.lang = this.currentLang;
    }
  }

  onChange(callback) {
    this.listeners.push(callback);
  }

  notifyListeners() {
    this.listeners.forEach((cb) => {
      try { cb(this.currentLang); } catch (e) { console.error(e); }
    });
  }
}

export const i18n = new I18nManager();
export const t = (key, fallback = '', params = null) => i18n.t(key, fallback, params);
